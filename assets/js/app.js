    const menuToggle = document.getElementById('menu-toggle');
    const siteMenu = document.getElementById('site-menu');

    function closeMenu() {
        siteMenu.classList.remove('open');
        menuToggle.setAttribute('aria-expanded', 'false');
        menuToggle.setAttribute('aria-label', 'Abrir menu');
        menuToggle.textContent = '☰';
    }

    menuToggle.addEventListener('click', () => {
        const isOpen = siteMenu.classList.toggle('open');
        menuToggle.setAttribute('aria-expanded', String(isOpen));
        menuToggle.setAttribute('aria-label', isOpen ? 'Fechar menu' : 'Abrir menu');
        menuToggle.textContent = isOpen ? '✕' : '☰';
    });

    siteMenu.querySelectorAll('a').forEach(link => link.addEventListener('click', closeMenu));

    const mainNavLinks = [...document.querySelectorAll('.nav a')];
    mainNavLinks.forEach(link => {
        link.addEventListener('click', () => {
        mainNavLinks.forEach(item => {
            item.classList.toggle('active', item === link);
            item.toggleAttribute('aria-current', item === link);
        });
        });
    });

    const appList = document.getElementById('app-list');
    const appsSection = document.getElementById('apps');
    const title = document.getElementById('apps-title');
    const emptyState = document.getElementById('empty-state');
    const tabs = [...document.querySelectorAll('[data-category]')];

    function renderCategory(category) {
        const apps = categories[category];

        if (category === "promo") {
            renderPromotions(apps);
            return;
        }

        appList.innerHTML = apps.map(app => `
            <article class="app-card">

                <div class="app-icon">
                    <img
                        src="${app.icon}"
                        alt="${app.name} aplicativo"
                        width="72"
                        height="72"
                        loading="lazy"
                        decoding="async">
                </div>

                <div class="app-info">
                    <h3 class="app-name">${app.name}</h3>
                    <p class="app-sub">${app.sub}</p>
                    <p class="recommend">${app.description}</p>
                </div>

                <a
                    class="btn"
                    href="#contato"
                    aria-label="Registrar em ${app.name}">
                    Registrar
                </a>

            </article>
        `).join("");
    }

    function renderPromotions(promotions) {

        appList.innerHTML = `
            <div class="promo-grid">
                ${promotions.map((promo, index) => `
                    <article class="promo-card">
                        <img
                            src="${promo.image}"
                            alt="${promo.alt}"
                            width="408"
                            height="136"
                            ${index < 2 ? 'loading="eager"' : 'loading="lazy"'}
                            decoding="async">
                    </article>
                `).join("")}
            </div>
        `;
    }

    tabs.forEach(tab => {
        tab.addEventListener('click', () => {
        const category = tab.dataset.category;
        tabs.forEach(item => {
            const selected = item === tab;
            item.classList.toggle('active', selected);
            item.setAttribute('aria-selected', String(selected));
            item.tabIndex = selected ? 0 : -1;
        });
        renderCategory(category);
        });

        tab.addEventListener('keydown', event => {
        if (!['ArrowLeft','ArrowRight','Home','End'].includes(event.key)) return;
        event.preventDefault();
        const current = tabs.indexOf(tab);
        const next = event.key === 'ArrowLeft' ? (current - 1 + tabs.length) % tabs.length
            : event.key === 'ArrowRight' ? (current + 1) % tabs.length
            : event.key === 'Home' ? 0 : tabs.length - 1;
        tabs[next].focus();
        tabs[next].click();
        });
    });

    renderCategory('hot');